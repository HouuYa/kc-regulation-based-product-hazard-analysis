/**
 * 기준의 한글 명칭 뽑기 — 전기용품(KC 60335 계열) 전용
 *
 * 왜 필요한가
 *   화면이 "KC 60335-2-13" 처럼 번호만 보여 주고 있었다. 담당자가 그 번호만 보고
 *   무슨 기준인지 알 수 없다는 지적을 받았다.
 *
 *   이름이 없던 이유는 display_name 을 파일명에서 만들기 때문이다
 *   (parse-result-json.ts parseFilename). "1. KC 60335-2-13_result.json" 에는
 *   번호밖에 없다. 반면 부속서 문서는 파일명 괄호에 품목이 들어 있어
 *   ("10. 안전확인 부속서 16(유아용 캐리어)") item_name 이 이미 잘 채워져 있다.
 *   즉 이름이 비어 있는 것은 전기용품 계열뿐이고, 이 파일은 그 빈칸만 메운다.
 *
 * 왜 부속서까지 뽑지 않는가 (해 보고 접었다)
 *   처음에는 모든 문서의 표지 제목을 뽑으려 했는데 실측에서 두 가지가 나왔다.
 *     "안전기준준수 부속서 5(가구)"      → "4. 안전요구사항"   (본문 소제목을 집었다)
 *     "안전기준준수 부속서 1(가정용 섬유제품)" → "가정용섬유제품"    (표지 큰 글씨라
 *        OCR 이 글자마다 띄어 놓았고, 되붙이니 어절 경계가 사라졌다)
 *   둘 다 파일명에서 뽑은 item_name("가구", "가정용 섬유제품")보다 나쁘다.
 *   더 나은 값이 이미 있는데 굳이 위험한 추정을 얹을 이유가 없다.
 *
 * OCR 원문을 그대로 쓴다
 *   "전기 튜김기"(튀김기) 처럼 원본 OCR 에 오탈자가 섞여 있다. 고쳐 쓰고 싶지만
 *   그러지 않는다 — 우리가 문서에 없는 말을 지어내기 시작하면 화면의 어떤 글자가
 *   원문인지 알 수 없게 된다. 오탈자는 원본 파싱 품질 문제로 따로 다룰 일이다.
 */

/** "제2-34부: …" 처럼 부(部)를 가리키는 줄. 전기용품 계열 문서의 표제다 */
const PART_LINE = /제\s*\d+(?:-\d+)*\s*부\s*[:：]/;



/**
 * 파싱 결과 JSON 의 OCR 텍스트에서 제목 요소만 순서대로 뽑는다.
 * OCR 결과는 `<div data-label="title" …><h1>제목</h1></div>` 형태다.
 */
export function titleElements(ocrText: string): string[] {
  return [...ocrText.matchAll(/data-label="title"[^>]*>(?:<h1>)?([^<]{2,160})/g)]
    .map((m) => m[1].replace(/\s+/g, ' ').trim())
    .filter((s) => /[가-힣]/.test(s));
}

/**
 * 한글 명칭을 만든다. 전기용품 계열이 아니거나 표제를 못 찾으면 null 이다 —
 * 화면은 그때 파일명에서 뽑은 품목명으로 물러선다.
 *
 * 계열명("가정용 및 이와 유사한 전기기기의 안전성")은 떼고 부(部) 표제만 남긴다.
 *   - 40건이 전부 같은 계열명이라, 표에 나란히 놓으면 앞부분이 똑같은 줄이
 *     40개 늘어선다. 구분되는 것은 "제2-34부: 전동 압축기" 쪽이다.
 *   - OCR 이 계열명 앞머리("가정용")를 다른 요소로 떼어 놓은 문서가 몇 건 있는데
 *     (2-73, 2-55, 2-66), 계열명을 버리면 그 문제도 함께 사라진다. 없는 글자를
 *     우리가 채워 넣는 것보다 안 쓰는 편이 낫다.
 */
export function extractTitleKo(ocrText: string): string | null {
  const titles = titleElements(ocrText);

  // 표제는 표지 다음 본문 첫 장에 있다. 문서 뒤쪽의 소제목까지 뒤지면
  // "4. 안전요구사항" 같은 것을 집게 되므로 앞부분만 본다.
  const head = titles.slice(0, 12);

  const line = head.find((s) => PART_LINE.test(s));
  if (!line) return null;

  const at = line.search(PART_LINE);
  return line.slice(at).replace(/\s{2,}/g, ' ').trim();
}
