-- 056 캐시「기록」토큰도 센다 — 이것은 할인이 아니라 웃돈이다
--
-- 실측으로 드러난 것 (2026-09-08)
--   054 에서 캐시 적중(cached_tokens)을 세기 시작했는데, 적중률이 0% 였다. 왜 그런지
--   보려고 응답의 usage 원문을 열어 보니 칸이 하나 더 있었다.
--
--     "prompt_tokens_details": { "cached_tokens": 0, "cache_write_tokens": 3033 }
--
--   같은 프롬프트로 세 번 연속 불러도 매번 cached_tokens 0 · cache_write_tokens 3033
--   이었다. 즉 **매번 캐시에 쓰기만 하고 한 번도 읽지 못하고 있다.**
--
--   그런데 단가표(developers.openai.com/api/docs/pricing, 2026-09-08 확인)를 보면
--   캐시 기록은 일반 입력보다 **비싸다.**
--
--     gpt-5.6-terra  입력 $2.00 / 캐시 적중 $0.20 / 캐시 기록 $2.50   (100만 토큰당)
--     gpt-5.6-luna   입력 $0.20 / 캐시 적중 $0.02 / 캐시 기록 $0.25
--
--   적중이 한 번이라도 나면 남는 장사다(기록 1.25배 + 적중 0.1배 < 매번 1.0배).
--   하지만 지금처럼 기록만 하고 적중이 없으면 **입력의 1.25배를 내고 있는 셈**이고,
--   화면의 금액은 그만큼 실제보다 적게 보인다.
--
--   054 가 「모르는 것을 0 으로 세면 비용이 적어 보인다」고 적어 놓고, 정작 이 칸을
--   몰라서 같은 실수를 하고 있었다. 세지 않으면 보이지 않는다.
-- =============================================================================

alter table public.llm_call
  add column if not exists cache_write_tokens integer not null default 0;

comment on column public.llm_call.cache_write_tokens is
  '입력 토큰 중 캐시에 기록된 분량. input_tokens 에 포함된 값이며 단가가 일반 입력의 '
  '1.25배다 — 적중(cached_tokens)이 뒤따라야 이득이 난다(056)';
