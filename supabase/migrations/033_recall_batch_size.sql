-- =============================================================================
-- 리콜 수집 구간을 10건에서 5건으로 줄인다 — 실측으로 정한 값
--
-- 무엇이 잘못돼 있었나
--   `recalls-fetch` 가 52번 돌아 200 을 **한 번도** 받지 못했다. 502·504 만 쌓였다.
--   같은 시간대에 `standards-sync` 는 50/52 성공했으므로 인증·배포·DB 는 멀쩡했다.
--   리콜 경로만의 문제였다.
--
-- 왜 그런지 재 보았다 (배포 환경에 직접 요청을 보내 측정, 2026-09-04)
--
--     limit=1   6,983ms
--     limit=2  10,229ms
--     limit=3  12,663ms
--     limit=4  15,609ms
--
--   깨끗한 직선이다. 1건당 약 2,875ms, 기동·연결 등 고정비가 약 4,100ms.
--
--     걸리는 시간 ≈ 4,100 + 2,875 × 건수
--
--   028 이 정한 10건을 넣으면 32,850ms 다. Netlify 의 HTTP 프록시 제한이 약
--   30초이므로 **절벽 바로 너머**에 있었다. 자료가 있는 구간은 예외 없이 초과한다.
--   자료가 없는 구간(오프셋 2,260 이상)은 1,098ms 로 잘 끝났지만, 최근 52번은
--   오프셋이 순차로 도는 구간이라 전부 자료가 있는 쪽에 몰려 있었다.
--
--   028 의 10건은 재 보고 정한 값이 아니었다. "20건은 위험하니 10건" 정도의
--   짐작이었고, 그 짐작이 한 번도 맞은 적이 없다.
--
-- 왜 5건인가
--   5건이면 4,100 + 14,375 = 약 18,500ms 로 제한의 62% 다. 여유가 필요한 이유가
--   있다 — 관리자 코드가 우리 코드북에 없는 건은 AI 로 다시 분류하는데(전체의
--   1.8%, 2,259건 중 40건이 HF.S.STD), 그 건은 5~7초가 더 든다. 5건 배치에
--   그런 건이 하나 섞이면 약 24,500ms 로 여전히 안쪽이다. 6건이면 27초라 아슬하다.
--
-- 한 바퀴 도는 시간
--   승인 자료가 2,252건이므로 5건씩이면 451번이면 다 돈다. 구간 수 500 은 그대로
--   두므로 오프셋은 0~2,495 를 훑고, 5분 간격이니 한 바퀴에 약 41.7시간이다.
--   지금까지 "42시간"이라고 적어 두었던 것과 사실상 같다 — 다만 그때는 한 바퀴가
--   도는 게 아니라 매번 실패하고 있었다.
--
-- 근본 해법은 따로 있다
--   바뀐 것이 없는 자료까지 41시간마다 다시 훑는 것 자체가 낭비다. `updated_at`
--   커서로 새 자료·바뀐 자료만 처리하는 증분 수집이 제대로 된 답이고, 그것은
--   02 설계서에 P2 로 올라 있다. 이 마이그레이션은 "지금 한 번도 안 되던 것을
--   되게" 하는 데까지만 한다.
-- =============================================================================

create or replace function public.run_recall_batch()
returns text
language plpgsql
security definer
set search_path = ''
as $run_recall_batch$
declare
  -- 한 요청이 맡는 건수. 실측 4,100 + 2,875×n 과 30초 제한에서 나온 값이다.
  -- 이 값을 올리려면 반드시 다시 재고, 위 주석의 표를 갱신한다.
  c_limit constant int := 5;
  -- 구간 수. c_limit 을 곱한 값이 승인 자료 건수보다 커야 한 바퀴가 완성된다.
  c_slots constant int := 500;
  v_offset int;
begin
  v_offset := (floor(extract(epoch from now()) / 300)::int % c_slots) * c_limit;
  perform public.run_job_at(
    'recalls-fetch',
    'offset=' || v_offset || '&limit=' || c_limit
  );
  return format('리콜 구간 요청 offset=%s limit=%s', v_offset, c_limit);
end;
$run_recall_batch$;

revoke execute on function public.run_recall_batch() from public;
revoke execute on function public.run_recall_batch() from anon, authenticated;
