-- =============================================================================
-- HF.S.QC 의 확인 경로를 OTHER → LEGAL 로 바로잡는다
--
-- 003 의 초기값 규칙(코드 계통으로 자동 채움)은 HF.H*/HF.E*/HF.M.DES 를 TEST,
-- HF.M.REG*·HF.S.INFO* 를 LEGAL, HF.S.NATL*·HF.S.INTL* 를 GAP 으로 분류하고
-- 나머지는 전부 OTHER 로 떨어뜨렸다. HF.S.QC(품질검수 미비)가 그 "나머지"에
-- 끼어 OTHER 로 남아 있었다.
--
-- 그런데 정의(codebook 문서 §5.2)를 보면 "부품·완제품 품질 검수 기준 미비"
-- (M-SHELL 연계: "부품 검수 절차 미준수")라, CLAUDE.md §10 이 말하는 불법의
-- 정의("인증·표시·부품변경 재인증 등 의무 위반")에 정확히 들어맞는다. 실제로
-- 구현이력.md 라운드 69 가 이미 "고의성이 확인되지 않으면 QC 쪽(HF.S.QC)을,
-- 조사관이 위반으로 판단했으면 ILLEGAL 을 쓰라"고 이 코드를 HF.M.REG.ILLEGAL 과
-- 짝지어 법령 위반 축으로 쓰기로 정해 두었다.
--
-- 병행 점검 2단계(라운드 70, 불법 신호 ②)를 만드는 중에 route 값을 그대로
-- 읽어 쓰려다 이 어긋남을 발견했다. 04-1 §9가 "확인 경로 검수 화면은 규칙으로
-- 채운 초기값이 얼마나 맞는지 먼저 보고 정한다"고 미뤄 둔 바로 그 검수를
-- 이번에 한 항목 실측으로 했다.
-- =============================================================================

update codebook.hf_route
set route = 'LEGAL',
    note = '004 정정 — 003 초기값은 코드 계통 규칙에 안 걸려 OTHER 로 남아 있었으나, ' ||
           '정의(부품 검수 절차 미준수)가 CLAUDE.md §10 의 불법 정의와 일치하고 ' ||
           '구현이력.md 라운드 69 가 HF.M.REG.ILLEGAL 과 짝지어 법령 위반 축으로 쓰기로 정함',
    updated_at = now()
where code = 'HF.S.QC' and route <> 'LEGAL';
